export type District = { city: string; name: string; strict?: boolean }
const FOLD: Record<string, string> = { "ı": "i", "İ": "i", "I": "i", "ş": "s", "Ş": "s", "ğ": "g", "Ğ": "g", "ü": "u", "Ü": "u", "ö": "o", "Ö": "o", "ç": "c", "Ç": "c", "â": "a", "î": "i", "û": "u" }
const f = (s: string) => Array.from(s).map((c) => FOLD[c] ?? c.toLowerCase()).join("")

/**
 * Günlük dilde başka anlamı olan ya da çok kısa ilçe adları ("Tire", "Bor", "Of"...).
 * Bunlar yalnızca açık yön ekiyle ("Tire'ye", "Tireden") ya da "X den Tire", "Konya - Tire" gibi
 * bağlamla ilçe sayılır; çıplak yazıldığında sıradan kelime kabul edilir.
 */
const STRICT = new Set(["agin", "aralik", "bahce", "bala", "bor", "bulanik", "cal", "can", "cat", "cay", "celebi", "cinar", "damal", "delice", "derik", "dicle", "dikmen", "dinar", "emet", "evren", "gole", "gudul", "guney", "hamur", "han", "hanak", "hani", "hekimhan", "honaz", "idil", "kaman", "kangal", "kas", "kavak", "keban", "keles", "kemah", "korkut", "kose", "kosk", "kozan", "koşk", "kula", "kumru", "kurtun", "kuyucak", "maden", "mut", "of", "olur", "orta", "sarkoy", "savur", "selim", "siran", "sumbas", "sur", "susuz", "tavas", "tefenni", "termal", "tire", "torul", "tut", "ula", "ulus", "yunak", "zara"])

/** katlanmış ilçe adı -> { il, görünen ad } (tek kelimelik adlar; birden çok ilde aynı adı taşıyanlar eşlenmez) */
export const DISTRICTS: Map<string, District> = new Map()
for (const table of [RAW, EXTRA]) {
  for (const [city, list] of Object.entries(table)) {
    for (const name of list.split(",")) {
      if (name.includes(" ")) continue
      const k = f(name)
      if (!DISTRICTS.has(k)) DISTRICTS.set(k, { city, name, strict: STRICT.has(k) })
    }
  }
}
